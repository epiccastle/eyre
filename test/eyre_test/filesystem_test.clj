(defn process-filesystem-types
  "Process a filesystem result, replacing the :size, :used, :available and
  :capacity values on each entry of :filesystems with the type of the value
  (e.g. Long for integers, Double for ratios/doubles)."
  [result]
  (let [type-keys #{:size :used :available :capacity}]
    (update result :filesystems
            (fn [filesystems]
              (mapv (fn [entry]
                      (reduce (fn [m k]
                                (if (contains? entry k)
                                  (assoc m k (type (get entry k)))
                                  m))
                              entry
                              type-keys))
                    filesystems)))))

(defn process-docker-options
  "Process a filesystem result, finding each :options string in :filesystems
  that contains \"docker\" and truncating it at the first \"=\" sign, keeping
  only the part before the \"=\" and the \"=\" itself (everything after the
  \"=\" is thrown away)."
  [result]
  (update result :filesystems
          (fn [filesystems]
            (mapv (fn [entry]
                    (let [options (:options entry)]
                      (if (and (string? options)
                               (str/includes? options "docker")
                               (str/includes? options "="))
                        (assoc entry :options
                               (subs options 0 (inc (str/index-of options "="))))
                        entry)))
                  filesystems))))

