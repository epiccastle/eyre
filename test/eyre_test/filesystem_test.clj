(deftest gather-filesystem-linux-test
  (let [mock-out "===mount===
/dev/sda1 on / type ext4 (rw,relatime,data=ordered)
proc on /proc type proc (rw,nosuid,nodev,noexec,relatime)
tmpfs on /dev/shm type tmpfs (rw,nosuid,nodev)
===df===
Filesystem     1024-blocks  Used Available Capacity Mounted on
/dev/sda1          20511356 6789012  12655344      35% /
tmpfs               1631526       0   1631526       0% /dev/shm
===selinux===
Enforcing
===apparmor===
loaded:yes
42 profiles are loaded.
===sip===
===securelevel===
===end==="
        exec-fn (fn [_script] {:exit 0 :out mock-out :err ""})
        res (filesystem/gather-filesystem {:exec exec-fn :shell {:type :bash}})]
    (is (= 3 (count (:filesystems res))))
    (is (= {:device "/dev/sda1"
            :mount-point "/"
            :type "ext4"
            :options "rw,relatime,data=ordered"
            :size (* 20511356 1024)
            :used (* 6789012 1024)
            :available (* 12655344 1024)
            :capacity (double (/ 6789012 20511356))}
           (first (:filesystems res))))
    (is (= {:device "tmpfs"
            :mount-point "/dev/shm"
            :type "tmpfs"
            :options "rw,nosuid,nodev"
            :size (* 1631526 1024)
            :used 0
            :available (* 1631526 1024)
            :capacity 0.0}
           (last (:filesystems res))))
    (is (= {:selinux {:enabled true :mode :enforcing}
            :apparmor {:enabled true :profiles 42}}
           (get-in res [:features :security])))))

